export type ChatUiTranslate = (key: ChatUiMessageKey) => string;

const defaultT: ChatUiTranslate = key => CHAT_UI_DEFAULT_EN[key] ?? key;

export const ChatUiI18nContext = createContext<ChatUiTranslate>(defaultT);

export function ChatUiI18nProvider({
  t,
  children,
}: {
  t: ChatUiTranslate;
  children?: ReactNode;
}) {
  return <ChatUiI18nContext.Provider value={t}>{children}</ChatUiI18nContext.Provider>;
}

export function useChatUiT(): ChatUiTranslate {
  return useContext(ChatUiI18nContext);
}
